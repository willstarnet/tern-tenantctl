// Writes lens/catalog.luau: every tenantctl command that takes a positional argument, with its
// risk and arguments, read from tenantctl's own command registry. The lens offers these as
// actions on the records it shows. Needs a tenantctl checkout:
//
//   bun scripts/gen-catalog.ts [path/to/tenantctl]   (default ../tenantctl)
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const src = resolve(process.argv[2] ?? join(import.meta.dir, '..', '..', 'tenantctl'));
// Dynamic: the tenantctl checkout is chosen at run time (argv), so no static path exists.
const registry = await import(join(src, 'src/registry.ts'));
const { kebab } = await import(join(src, 'src/core/args.ts'));
// Release builds take their version from the git tag; package.json lags behind it.
const tag = Bun.spawnSync(['git', '-C', src, 'describe', '--tags', '--abbrev=0']).stdout.toString().trim();
const version: string = tag.replace(/^v/, '') || JSON.parse(readFileSync(join(src, 'package.json'), 'utf8')).version;

interface ArgSpec {
  name: string;
  required?: boolean;
  positional?: boolean;
  default?: unknown;
  type: string;
}
interface Command {
  domain: string;
  name: string;
  summary: string;
  risk: 'read' | 'write' | 'destructive';
  args: readonly ArgSpec[];
}
// Commands about the CLI itself, never about a tenant record.
const SKIP: Record<string, true> = { auth: true, config: true, tools: true, permissions: true, graph: true };

const lua = (s: string) => JSON.stringify(s);

const lines: string[] = [];
let count = 0;
for (const command of registry.COMMANDS as Command[]) {
  if (SKIP[command.domain]) continue;
  const positional = command.args.filter((a) => a.positional);
  if (positional.length === 0) continue;
  const flags = command.args.filter((a) => !a.positional && a.required && a.default === undefined);
  const bools = command.args.filter((a) => !a.positional && a.type === 'boolean').map((a) => lua(kebab(a.name)));
  const pos = positional
    .map((a) => `{ name = ${lua(kebab(a.name))}, required = ${a.required === true && a.default === undefined} }`)
    .join(', ');
  const req = flags.map((a) => lua(kebab(a.name))).join(', ');
  lines.push(
    '\t{',
    `\t\tid = ${lua(registry.commandId(command))},`,
    `\t\tsummary = ${lua(command.summary)},`,
    `\t\trisk = ${lua(command.risk)},`,
    `\t\tpositional = { ${pos} },`,
    `\t\tflags = ${req ? `{ ${req} }` : '{}'},`,
    `\t\tbools = ${bools.length ? `{ ${bools.join(', ')} }` : '{}'},`,
    '\t},',
  );
  count++;
}

const out = `--!strict
-- Generated by scripts/gen-catalog.ts from tenantctl ${version}'s command registry: every command that takes a
-- positional argument. Do not edit by hand; regenerate after upgrading tenantctl.

export type Arg = { name: string, required: boolean }
export type Command = {
	-- \`intune devices sync\`
	id: string,
	summary: string,
	-- "read" | "write" | "destructive"
	risk: string,
	-- positional arguments in order (kebab-case flag names)
	positional: { Arg },
	-- required flags that are not positional
	flags: { string },
	-- flags that take no value, for reading a command line
	bools: { string },
}

local commands: { Command } = {
${lines.join('\n')}
}

return {
	version = ${lua(version)},
	commands = commands,
}
`;

writeFileSync(join(import.meta.dir, '..', 'lens', 'catalog.luau'), out);
console.log(`gen-catalog: ${count} commands from tenantctl ${version} at ${src}`);
